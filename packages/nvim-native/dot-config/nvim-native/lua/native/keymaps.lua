local function map(lhs, rhs, desc) vim.keymap.set("n", lhs, rhs, { desc = desc }) end
local project = require("native.project")
map("<leader>ff", function() require("mini.pick").builtin.files({}, { source = { cwd = project.root() } }) end, "Find project files")
map("<leader>sg", function() require("mini.pick").builtin.grep_live({}, { source = { cwd = project.root() } }) end, "Search project text")
map("<S-h>", "<cmd>bprevious<cr>", "Previous buffer")
map("<S-l>", "<cmd>bnext<cr>", "Next buffer")
map("<leader>bb", "<cmd>buffer #<cr>", "Alternate buffer")
map("<leader>bd", "<cmd>bdelete<cr>", "Close buffer")
map("<leader>wf", function() require("mini.pick").builtin.files({}, { source = { cwd = vim.g.wiki_root } }) end, "Find wiki page")
map("<leader>ws", function() require("mini.pick").builtin.grep_live({}, { source = { cwd = vim.g.wiki_root } }) end, "Search wiki text")
map("<leader>cp", "<cmd>NativeProject<cr>", "Project / Python environment")
map("<leader>fb", function() require("mini.pick").builtin.buffers() end, "Buffers")
map("<leader>fh", function() require("mini.pick").builtin.help() end, "Help")
map("<leader>e", "<cmd>Explore<cr>", "File browser")
map("<leader>cf", function()
  require("conform").format({ async = true, lsp_format = "fallback" })
end, "Format buffer")
map("<leader>cr", vim.lsp.buf.rename, "Rename symbol")
map("<leader>ca", vim.lsp.buf.code_action, "Code action")
map("<leader>cd", vim.diagnostic.open_float, "Line diagnostics")
map("<leader>xx", vim.diagnostic.setqflist, "All diagnostics")
map("<leader>ud", function() vim.diagnostic.enable(not vim.diagnostic.is_enabled()) end, "Toggle diagnostics")
-- Reserve <leader>w for wiki.vim's default mappings.
map("<leader>fs", "<cmd>write<cr>", "Save")
map("<leader>q", "<cmd>quit<cr>", "Quit")
